STATE_NAMES = {code: name for name, code in STATE_CODES.items()}

_CODES_BY_FOLDED_NAME = {name.casefold(): code for name, code in STATE_CODES.items()}


def to_code(value: str) -> str:
    """Return the code for a state name or code in any case ("Ohio", "oh" -> "OH").

    Anything else is returned upper-cased, so the caller's validation can reject it.
    """
    value = " ".join(value.split())
    return _CODES_BY_FOLDED_NAME.get(value.casefold(), value.upper())
